// src/components/charts/DiseaseCoverageMap.tsx
// Interactive choropleth that shows every country/territory reporting the
// current disease, so a disease page opens with a picture instead of a
// download link.
//
// Reporting patches roll up: a location backed only by provincial feeds paints
// its parent polygon and advertises the regional series count on hover.
// Territories that have no polygon in the bundled extract (Hong Kong and
// Taiwan) are plotted as HTML markers on the geo projection rather than
// silently dropped. The page uses the lean map registry, without scatter
// or visual-map components.

import { useEffect, useMemo, useRef, useState } from 'react';
import ReactEChartsCore from '../../lib/echartsReact';
import echarts from '../../lib/echartsMapCoverage';
import featureIsoJson from '../../lib/data/world-feature-iso.json' with { type: 'json' };
import { loadDiseaseDataset, type DiseaseDataset } from './diseaseDataset';
import ChartResultActions from './ChartResultActions';
import { pngFromCanvases } from './chartExport';

type Lang = 'en' | 'zh' | 'fr';
type Metric = 'coverage' | 'cases' | 'deaths';

const MAP_NAME = 'world-countries-lnglat';
const LOCAL_WORLD_MAP_URL = '/data/world.json';

/** feature display name -> ISO 3166-1 alpha-2 (generated by scripts/build-world-feature-iso.mjs). */
const FEATURE_NAME_TO_ISO: Record<string, string> = (
  featureIsoJson as { featureNameToIso: Record<string, string> }
).featureNameToIso;

const ISO_TO_FEATURE_NAME: Record<string, string> = (() => {
  const inverted: Record<string, string> = {};
  for (const [featureName, code] of Object.entries(FEATURE_NAME_TO_ISO)) {
    if (!inverted[code]) inverted[code] = featureName;
  }
  return inverted;
})();

// Territories that publish surveillance data but own no polygon in the extract.
// They are drawn as HTML dots on the geo projection so the disease page does
// not have to ship ECharts scatter or visual-map components.
const TERRITORY_MARKERS: Record<string, [number, number]> = {
  HK: [114.17, 22.32],
  TW: [121, 23.7],
};

function bucketColor(value: number, min: number, max: number, ramp: string[]): string {
  if (!(max > min)) return ramp[ramp.length - 1];
  const ratio = Math.min(1, Math.max(0, (value - min) / (max - min)));
  return ramp[Math.min(ramp.length - 1, Math.round(ratio * (ramp.length - 1)))];
}

interface LocationCoverage {
  code: string;
  name: string;
  cases: number;
  deaths: number;
  /** number of sub-national series rolled into this location */
  regions: number;
  /** true when the location publishes a national-level series of its own */
  national: boolean;
}

interface Props {
  dataUrl?: string;
  initialLanguage?: Lang;
  height?: number;
}

function ui(lang: Lang, en: string, zh: string, fr: string): string {
  return lang === 'zh' ? zh : lang === 'fr' ? fr : en;
}

function paletteFor(theme: 'light' | 'dark') {
  // Tokens mirror CountriesMapView so both map surfaces stay visually aligned.
  return theme === 'light'
    ? {
        mapBg: 'linear-gradient(180deg, #eef4fa 0%, #dde8f2 100%)',
        areaBorder: '#b6c8d8',
        areaHover: '#e4edf5',
        noData: '#e7eef5',
        supported: '#0f766e',
        supportedBorder: '#0d6d8c',
        ramp: ['#cdeee7', '#7ad3c1', '#2f9e8f', '#0f766e', '#0b4f4a'],
        tooltipBg: '#ffffff',
        tooltipBorder: '#c7d7e6',
        text: '#17304d',
        muted: '#657b92',
      }
    : {
        mapBg: 'linear-gradient(180deg, #152233 0%, #111b28 100%)',
        areaBorder: '#102033',
        areaHover: '#25374d',
        noData: '#1f2d3f',
        supported: '#14b8a6',
        supportedBorder: '#0d9488',
        ramp: ['#1f4f4a', '#14685f', '#0e9488', '#14b8a6', '#5eead4'],
        tooltipBg: '#162334',
        tooltipBorder: '#304156',
        text: '#e2e8f0',
        muted: '#94a3b8',
      };
}

/** Roll sub-national series into their parent country and total each metric. */
export function buildLocationCoverage(dataset: DiseaseDataset, lang: Lang): LocationCoverage[] {
  const series = dataset?.country_series ?? {};
  const rolled = new Map<string, LocationCoverage>();

  for (const [rawCode, entry] of Object.entries(series)) {
    const code = String(rawCode).toUpperCase();
    const parent = code.includes('-') ? code.split('-')[0] : code;
    const isNational = !code.includes('-');

    const hasValues =
      Array.isArray(entry?.dates) &&
      entry.dates.length > 0 &&
      ((Array.isArray(entry.cases) && entry.cases.some((value) => value !== null)) ||
        (Array.isArray(entry.deaths) && entry.deaths.some((value) => value !== null)));
    if (!hasValues) continue;

    const label =
      (lang === 'zh' ? entry?.name_zh : lang === 'fr' ? entry?.name_fr || entry?.name_en : entry?.name_en) || code;
    const existing = rolled.get(parent);
    const cases = Number(entry?.total_cases ?? 0) || 0;
    const deaths = Number(entry?.total_deaths ?? 0) || 0;

    if (!existing) {
      rolled.set(parent, { code: parent, name: label, cases, deaths, regions: isNational ? 0 : 1, national: isNational });
      continue;
    }
    // Prefer a national record's own display name and roll everything else up.
    existing.cases += cases;
    existing.deaths += deaths;
    if (!isNational) existing.regions += 1;
    if (isNational && !existing.national) {
      existing.national = true;
      existing.name = label;
    }
  }

  return [...rolled.values()].sort((a, b) => a.name.localeCompare(b.name, lang === 'zh' ? 'zh' : 'en'));
}

export default function DiseaseCoverageMap({ dataUrl, initialLanguage = 'en', height = 420 }: Props) {
  const lang = initialLanguage;
  const chartRef = useRef<any>(null);
  const shellRef = useRef<HTMLDivElement>(null);
  const frameRef = useRef<HTMLDivElement>(null);
  const [theme, setTheme] = useState<'light' | 'dark'>('dark');
  const [mapReady, setMapReady] = useState(false);
  const [mapFailed, setMapFailed] = useState(false);
  const [dataset, setDataset] = useState<DiseaseDataset | null>(null);
  const [datasetFailed, setDatasetFailed] = useState(false);
  const [metric, setMetric] = useState<Metric>('coverage');
  const [resetToken, setResetToken] = useState(0);

  useEffect(() => {
    const requested = new URLSearchParams(window.location.search).get('map_metric');
    if (requested === 'coverage' || requested === 'cases' || requested === 'deaths') setMetric(requested);
  }, []);

  useEffect(() => {
    const root = document.documentElement;
    const update = () => setTheme(root.getAttribute('data-theme') === 'light' ? 'light' : 'dark');
    update();
    const observer = new MutationObserver(update);
    observer.observe(root, { attributes: true, attributeFilter: ['data-theme'] });
    return () => observer.disconnect();
  }, []);

  // loadDiseaseDataset shares a module-level cache with the disease charts, so
  // adding this island costs no extra network request on a disease page.
  useEffect(() => {
    let cancelled = false;
    if (!dataUrl) return;
    loadDiseaseDataset(dataUrl)
      .then((payload) => {
        if (cancelled) return;
        setDataset(payload);
        setDatasetFailed(false);
      })
      .catch(() => {
        if (!cancelled) setDatasetFailed(true);
      });
    return () => {
      cancelled = true;
    };
  }, [dataUrl]);

  // Load the bundled world extract once; reuse it when another island on the
  // page has already registered the same projection.
  useEffect(() => {
    if (echarts.getMap(MAP_NAME)) {
      setMapReady(true);
      return;
    }
    let cancelled = false;
    fetch(LOCAL_WORLD_MAP_URL)
      .then((response) => {
        if (!response.ok) throw new Error(`HTTP ${response.status}`);
        return response.json();
      })
      .then((geoJson) => {
        if (cancelled) return;
        echarts.registerMap(MAP_NAME, geoJson);
        setMapReady(true);
      })
      .catch(() => {
        if (!cancelled) setMapFailed(true);
      });
    return () => {
      cancelled = true;
    };
  }, []);

  const locations = useMemo(() => (dataset ? buildLocationCoverage(dataset, lang) : []), [dataset, lang]);

  const drawn = useMemo(
    () =>
      locations.filter((location) => Boolean(ISO_TO_FEATURE_NAME[location.code] || TERRITORY_MARKERS[location.code])),
    [locations],
  );

  const hasCases = drawn.some((location) => location.cases > 0);
  const hasDeaths = drawn.some((location) => location.deaths > 0);
  const activeMetric: Metric =
    (metric === 'cases' && !hasCases) || (metric === 'deaths' && !hasDeaths) ? 'coverage' : metric;

  const regionalSeriesCount = useMemo(
    () => drawn.reduce((sum, location) => sum + location.regions, 0),
    [drawn],
  );

  const numberFormat = useMemo(
    () => new Intl.NumberFormat(lang === 'zh' ? 'zh-CN' : lang === 'fr' ? 'fr-FR' : 'en-US'),
    [lang],
  );

  const palette = useMemo(() => paletteFor(theme), [theme]);
  const polygonLocations = useMemo(
    () => drawn.filter((location) => Boolean(ISO_TO_FEATURE_NAME[location.code])),
    [drawn],
  );
  const territoryLocations = useMemo(
    () => drawn.filter((location) => Boolean(TERRITORY_MARKERS[location.code])),
    [drawn],
  );
  const locationColors = useMemo(() => {
    const valueOf = (location: LocationCoverage) => {
      if (activeMetric === 'cases') return Math.log10(location.cases + 1);
      if (activeMetric === 'deaths') return Math.log10(location.deaths + 1);
      return 1;
    };
    const values = [...polygonLocations, ...territoryLocations].map(valueOf);
    const min = values.length ? Math.min(...values) : 0;
    const max = values.length ? Math.max(...values) : 1;
    return new Map(
      drawn.map((location) => [
        location.code,
        activeMetric === 'coverage' ? palette.supported : bucketColor(valueOf(location), min, max, palette.ramp),
      ]),
    );
  }, [activeMetric, drawn, palette, polygonLocations, territoryLocations]);

  const option = useMemo(() => {
    if (!mapReady) return {};
    const byFeature = new Map(
      polygonLocations.map((location) => [ISO_TO_FEATURE_NAME[location.code], location]),
    );

    return {
      backgroundColor: 'transparent',
      tooltip: {
        trigger: 'item',
        backgroundColor: palette.tooltipBg,
        borderColor: palette.tooltipBorder,
        textStyle: { color: palette.text },
        formatter: (params: { name?: string }) => {
          const location = params?.name ? byFeature.get(params.name) : undefined;
          if (!location) return params?.name || '';
          const rows = [`<strong>${location.name}</strong>`];
          if (activeMetric === 'cases') {
            rows.push(`${ui(lang, 'Reported cases', '累计报告病例', 'Cas déclarés')}: <strong>${numberFormat.format(location.cases)}</strong>`);
          }
          if (activeMetric === 'deaths') {
            rows.push(`${ui(lang, 'Reported deaths', '累计报告死亡', 'Décès déclarés')}: <strong>${numberFormat.format(location.deaths)}</strong>`);
          }
          if (location.regions) {
            rows.push(`<span style="color:${palette.muted}">${ui(lang, `${location.regions} sub-national series`, `${location.regions} 个地区数据集`, `${location.regions} séries infranationales`)}</span>`);
          }
          rows.push(`<span style="color:${palette.muted}">${ui(lang, 'Click to open country page ↗', '单击打开国家页 ↗', 'Cliquez pour ouvrir la page du pays ↗')}</span>`);
          return rows.join('<br/>');
        },
      },
      geo: {
        map: MAP_NAME,
        roam: true,
        scaleLimit: { min: 0.7, max: 8 },
        selectedMode: false,
        itemStyle: { areaColor: palette.noData, borderColor: palette.areaBorder, borderWidth: 0.4 },
        emphasis: { label: { show: false }, itemStyle: { areaColor: palette.areaHover } },
        label: { show: false },
        regions: polygonLocations.map((location) => ({
          name: ISO_TO_FEATURE_NAME[location.code],
          itemStyle: { areaColor: locationColors.get(location.code) },
        })),
      },
    };
  }, [activeMetric, lang, locationColors, mapReady, numberFormat, palette, polygonLocations]);

  // Keep canvases sharp across orientation changes and narrow viewports.
  useEffect(() => {
    const resize = () => chartRef.current?.getEchartsInstance?.()?.resize();
    window.addEventListener('resize', resize);
    return () => window.removeEventListener('resize', resize);
  }, []);

  const openLocation = (code?: string) => {
    if (!code) return;
    const prefix = lang === 'zh' ? '/zh' : lang === 'fr' ? '/fr' : '';
    window.location.href = `${prefix}/countries/${code.toLowerCase()}/`;
  };

  const [markers, setMarkers] = useState<Array<LocationCoverage & { x: number; y: number }>>([]);
  useEffect(() => {
    if (!mapReady) return;
    const chart = chartRef.current?.getEchartsInstance?.();
    if (!chart) return;
    let frame = 0;
    const update = () => {
      const next = territoryLocations.flatMap((location) => {
        const pixel = chart.convertToPixel({ geoIndex: 0 }, TERRITORY_MARKERS[location.code]);
        if (!Array.isArray(pixel) || pixel.some((value) => !Number.isFinite(value))) return [];
        return [{ ...location, x: pixel[0], y: pixel[1] }];
      });
      setMarkers(next);
    };
    const schedule = () => {
      cancelAnimationFrame(frame);
      frame = requestAnimationFrame(update);
    };
    schedule();
    chart.on('georoam', schedule);
    chart.on('finished', schedule);
    return () => {
      cancelAnimationFrame(frame);
      chart.off('georoam', schedule);
      chart.off('finished', schedule);
    };
  }, [mapReady, option, resetToken, territoryLocations]);

  const handleEvents = useMemo(
    () => ({
      click: (params: { name?: string }) => {
        const code = params?.name ? FEATURE_NAME_TO_ISO[params.name] : undefined;
        if (!code || !drawn.some((location) => location.code === code)) return;
        openLocation(code);
      },
    }),
    [drawn, lang],
  );

  const zoom = (factor: number) => {
    const chart = chartRef.current?.getEchartsInstance?.();
    if (!chart) return;
    chart.dispatchAction({
      type: 'geoRoam',
      componentType: 'geo',
      geoIndex: 0,
      zoom: factor,
      originX: chart.getWidth() / 2,
      originY: chart.getHeight() / 2,
    });
  };
  const resetZoom = () => setResetToken((token) => token + 1);

  // Progressive enhancement: the server-rendered country grid below already
  // lists every reporting location, so failures render nothing rather than an
  // empty frame.
  if (!dataUrl || datasetFailed || mapFailed) return null;

  if (!dataset || !mapReady) {
    return (
      <div
        className="chart-loading-shell"
        role="status"
        aria-busy="true"
        aria-label={ui(lang, 'Loading coverage map', '覆盖范围地图加载中', 'Chargement de la carte de couverture')}
      >
        <div className="chart-loading-toolbar" aria-hidden="true">
          <span className="chart-loading-pill w-20" />
          <span className="chart-loading-pill w-28" />
          <span className="chart-loading-pill w-24" />
        </div>
        <div className="chart-loading-line w-3/5" aria-hidden="true" />
        <div className="chart-loading-panel" style={{ height }} aria-hidden="true" />
      </div>
    );
  }

  if (!drawn.length) return null;

  const metricLabel = (value: Metric) =>
    value === 'cases'
      ? ui(lang, 'Reported cases', '累计报告病例', 'Cas déclarés')
      : value === 'deaths'
        ? ui(lang, 'Reported deaths', '累计报告死亡', 'Décès déclarés')
        : ui(lang, 'Reporting locations', '报告国家/地区', 'Lieux déclarant');

  const zoomLabel = ui(lang, 'Map zoom', '地图缩放', 'Zoom de la carte');

  const share = () => {
    const url = new URL(window.location.href);
    url.searchParams.set('map_metric', activeMetric);
    return url.toString();
  };

  return (
    <div className="disease-coverage-map panel-fullscreen" ref={shellRef}>
      <div className="disease-coverage-toolbar">
        <span className="site-control-pill" style={{ fontSize: '.7rem' }}>
          {ui(lang, `${drawn.length} locations`, `${drawn.length} 个报告国家/地区`, `${drawn.length} lieux`)}
          {regionalSeriesCount > 0
            ? ` · ${ui(
                lang,
                `${regionalSeriesCount} regional series`,
                `${regionalSeriesCount} 个地区数据集`,
                `${regionalSeriesCount} séries régionales`,
              )}`
            : ''}
        </span>
        <span className="disease-coverage-spacer" />
        {(['coverage', 'cases', 'deaths'] as Metric[]).map((value) => {
          const disabled = (value === 'cases' && !hasCases) || (value === 'deaths' && !hasDeaths);
          const active = activeMetric === value;
          return (
            <button
              key={value}
              type="button"
              className="site-control-pill focus-ring"
              style={{
                fontSize: '.7rem',
                cursor: disabled ? 'not-allowed' : 'pointer',
                opacity: disabled ? 0.45 : 1,
                borderColor: active ? palette.supported : undefined,
                color: active ? palette.supported : undefined,
              }}
              aria-pressed={active}
              disabled={disabled}
              onClick={() => setMetric(value)}
            >
              {metricLabel(value)}
            </button>
          );
        })}
        <ChartResultActions
          lang={lang}
          shellRef={shellRef}
          onShare={share}
          pngFilename="gids-disease-coverage.png"
          getPng={() => frameRef.current ? pngFromCanvases(frameRef.current, markers.map((marker) => ({
            x: marker.x,
            y: marker.y,
            color: locationColors.get(marker.code) ?? palette.supported,
            radius: 6,
          }))) : null}
        />
      </div>
      <div
        ref={frameRef}
        className="disease-coverage-frame"
        style={{
          position: 'relative',
          height: `clamp(300px, 44vw, ${height}px)`,
          overflow: 'hidden',
          background: palette.mapBg,
          border: `1px solid ${palette.tooltipBorder}`,
        }}
        role="img"
        aria-label={ui(
          lang,
          `World map highlighting ${drawn.length} countries and territories reporting this disease`,
          `世界地图：高亮显示报告该疾病的 ${drawn.length} 个国家和地区`,
          `Carte mondiale : ${drawn.length} pays et territoires déclarant cette maladie`,
        )}
      >
        <ReactEChartsCore
          key={resetToken}
          ref={chartRef}
          echarts={echarts}
          option={option}
          style={{ height: '100%', width: '100%' }}
          onEvents={handleEvents}
          notMerge
        />
        {markers.map((marker) => (
          <button
            key={marker.code}
            type="button"
            className="coverage-territory-marker focus-ring"
            style={{
              left: marker.x,
              top: marker.y,
              background: locationColors.get(marker.code),
              borderColor: palette.supportedBorder,
            }}
            aria-label={ui(lang, `Open ${marker.name}`, `打开${marker.name}`, `Ouvrir ${marker.name}`)}
            onClick={() => openLocation(marker.code)}
          />
        ))}
        {activeMetric !== 'coverage' && (
          <span className="coverage-scale" style={{ color: palette.muted }}>
            <i style={{ background: `linear-gradient(90deg, ${palette.ramp.join(',')})` }} />
            {ui(lang, 'lower', '低', 'faible')}
            <span aria-hidden="true">–</span>
            {ui(lang, 'higher', '高', 'élevé')}
          </span>
        )}
        <div
          style={{ position: 'absolute', top: 8, right: 8, display: 'flex', flexDirection: 'column', gap: '.25rem' }}
          role="group"
          aria-label={zoomLabel}
        >
          <button
            type="button"
            className="site-control-pill focus-ring"
            style={{ fontSize: '.72rem', cursor: 'pointer', minWidth: '1.75rem' }}
            aria-label={ui(lang, 'Zoom in', '放大', 'Zoom avant')}
            onClick={() => zoom(1.3)}
          >
            +
          </button>
          <button
            type="button"
            className="site-control-pill focus-ring"
            style={{ fontSize: '.72rem', cursor: 'pointer', minWidth: '1.75rem' }}
            aria-label={ui(lang, 'Zoom out', '缩小', 'Zoom arrière')}
            onClick={() => zoom(0.8)}
          >
            −
          </button>
          <button
            type="button"
            className="site-control-pill focus-ring"
            style={{ fontSize: '.72rem', cursor: 'pointer', minWidth: '1.75rem' }}
            aria-label={ui(lang, 'Reset zoom', '重置缩放', 'Réinitialiser le zoom')}
            onClick={resetZoom}
          >
            ↺
          </button>
        </div>
        <span style={{ position: 'absolute', bottom: 8, right: 8, color: palette.muted, fontSize: '.65rem' }}>
          {ui(
            lang,
            'Scroll to zoom · drag to pan',
            '滚轮缩放 · 拖拽平移',
            'Molette pour zoomer · glisser pour déplacer',
          )}
        </span>
      </div>
      <p className="disease-coverage-note" style={{ color: palette.muted }}>
        {activeMetric === 'coverage'
          ? ui(
              lang,
              'Shaded locations publish surveillance data for this disease. Regional series are rolled up into their parent country.',
              '着色地区表示该疾病已有监测数据；地区级数据已汇总至所属国家。',
              'Les lieux colorés publient des données de surveillance pour cette maladie. Les séries régionales sont agrégées à leur pays.',
            )
          : ui(
              lang,
              'Totals use a logarithmic scale so that smaller programmes stay visible next to national totals.',
              '总量采用对数刻度，以便小规模数据在大国数据旁仍然可见。',
              'Les totaux utilisent une échelle logarithmique pour rester visibles face aux totaux nationaux.',
            )}
      </p>
    </div>
  );

}
