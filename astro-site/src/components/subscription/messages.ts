import { translateUi } from '../../utils/i18n';

export function subscriptionText(locale: 'en' | 'zh' | 'fr') {
  return <T,>(en: T, zh: T, fr?: T): T => locale === 'fr' ? (fr ?? (typeof en === 'string' ? translateUi(en) as T : en)) : locale === 'zh' ? zh : en;
}

